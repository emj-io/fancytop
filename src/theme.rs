//! Colour themes: every colour and gradient the UI draws with, cycled with `c` / `C`.

use std::sync::LazyLock;

use crate::ui::{Gradient, Rgb};

pub struct Theme {
    pub name: &'static str,
    /// Painted behind everything; `None` leaves the terminal's own background.
    pub bg: Option<Rgb>,
    pub fg: Rgb,
    pub dim: Rgb,
    pub faint: Rgb,
    pub border: Rgb,
    pub header_bg: Rgb,
    /// Panel names and the peak-hold marker.
    pub hi: Rgb,
    /// Focused border, key hints and the drop preview.
    pub accent: Rgb,
    /// Text drawn on `accent`.
    pub on_accent: Rgb,
    /// Shading where a dragged window would land.
    pub shade: Rgb,

    pub mem_wired: Rgb,
    pub mem_app: Rgb,
    pub mem_comp: Rgb,
    pub mem_cache: Rgb,
    pub mem_free: Rgb,

    /// Load: CPU, memory pressure, processes.
    pub heat: Gradient,
    pub gpu: Gradient,
    pub mem: Gradient,
    pub disk: Gradient,
    pub net: Gradient,
    pub title: Gradient,
}

impl Theme {
    /// Look a theme up by name, ignoring case, spaces and hyphens.
    pub fn find(name: &str) -> Option<usize> {
        let key = |s: &str| s.chars().filter(|c| c.is_alphanumeric()).collect::<String>().to_lowercase();
        let want = key(name);
        THEMES.iter().position(|t| key(t.name) == want)
    }
}

fn g(stops: &[(f64, Rgb)]) -> Gradient {
    Gradient::new(stops)
}

